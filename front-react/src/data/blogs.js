// Nota de lectura: Define una función o método con los parámetros que necesita esta parte del flujo.
export function crearBlog(datos) {
  // Nota de lectura: Transforma cada elemento, por ejemplo de entidad a DTO o de dato a fila visual.
  const nuevoId = blogs.length ? Math.max(...blogs.map((b) => b.id)) + 1 : 1
  // Nota de lectura: Define nuevo, que se utiliza en las instrucciones siguientes.
  const nuevo = { ...datos, id: nuevoId }
  // Nota de lectura: Invoca la operación indicada con los argumentos de este bloque.
  blogs.push(nuevo)
  // Nota de lectura: Entrega el resultado de la función o la interfaz que debe renderizar React.
  return { ...nuevo }
// Nota de lectura: Cierra o delimita la expresión, bloque o elemento abierto en las líneas anteriores.
}

// UPDATE (devuelve el blog actualizado o null)
// Nota de lectura: Define una función o método con los parámetros que necesita esta parte del flujo.
export function actualizarBlog(id, cambios) {
  // Nota de lectura: Define indice, que se utiliza en las instrucciones siguientes.
  const indice = blogs.findIndex((b) => b.id === Number(id))
  // Nota de lectura: Evalúa una condición. El bloque solo continúa por esta rama si se cumple.
  if (indice === -1) return null
  // Nota de lectura: Asigna o compara el valor de esta parte de la expresión.
  blogs[indice] = { ...blogs[indice], ...cambios, id: blogs[indice].id }
  // Nota de lectura: Entrega el resultado de la función o la interfaz que debe renderizar React.
  return { ...blogs[indice] }
// Nota de lectura: Cierra o delimita la expresión, bloque o elemento abierto en las líneas anteriores.
}

